describe('startServer - failure / rollback path', () => {
    test('rejects and cleans up when HTTP port is already in use', async () => {
        const port = await getFreePort();

        const blocker = http.createServer();
        await new Promise((resolve) => blocker.listen(port, resolve));

        try {
            const config = minimalConfig({ listen: { http: port, https: null } });

            await assert.rejects(
                () => startServer(config, silentLogger),
                /EADDRINUSE/
            );

            const freePort = await getFreePort();
            const retryConfig = minimalConfig({ listen: { http: freePort, https: null } });
            await assert.doesNotReject(() => startServer(retryConfig, silentLogger));
        } finally {
            await new Promise((resolve) => blocker.close(resolve));
        }
    });
});

