describe('startServer - HTTP/HTTPS combinations', () => {
    test('starts HTTP only when https is null', async () => {
        const port = await getFreePort();
        const config = minimalConfig({ listen: { http: port, https: null } });

        const result = await startServer(config, silentLogger);

        assert.ok(result.httpServer, 'httpServer should be created');
        assert.equal(result.httpsServer, null, 'httpsServer should stay null');
    });

    test('starts neither when both listen ports are null', async () => {
        const config = minimalConfig({ listen: { http: null, https: null } });

        const result = await startServer(config, silentLogger);

        assert.equal(result.httpServer, null);
        assert.equal(result.httpsServer, null);
    });

    test('starts HTTPS via self-signed cert auto-generation (tls.js ensureCertificate)', async () => {
        const httpsPort = await getFreePort();
        const tmpDir = fs.mkdtempSync(path.join(os.tmpdir(), 'nexus-tls-'));
        const certPath = path.join(tmpDir, 'cert.pem');
        const keyPath = path.join(tmpDir, 'key.pem');

        const config = minimalConfig({
            listen: { http: null, https: httpsPort },
            tls: { certPath, keyPath, sni: false }
        });

        const result = await startServer(config, silentLogger);

        assert.ok(result.httpsServer, 'httpsServer should be created');
        assert.ok(fs.existsSync(certPath), 'cert should be auto-generated by tls.js');
        assert.ok(fs.existsSync(keyPath), 'key should be auto-generated by tls.js');
    });

    test('starts both HTTP and HTTPS concurrently', async () => {
        const httpPort = await getFreePort();
        const httpsPort = await getFreePort();
        const tmpDir = fs.mkdtempSync(path.join(os.tmpdir(), 'nexus-tls-'));

        const config = minimalConfig({
            listen: { http: httpPort, https: httpsPort },
            tls: { certPath: path.join(tmpDir, 'cert.pem'), keyPath: path.join(tmpDir, 'key.pem'), sni: false }
        });

        const result = await startServer(config, silentLogger);

        assert.ok(result.httpServer);
        assert.ok(result.httpsServer);
    });
});

