describe('startServer - guard conditions', () => {
    test('throws if called twice without shutdownServer()', async () => {
        const port = await getFreePort();
        const config = minimalConfig({ listen: { http: port, https: null } });

        await startServer(config, silentLogger);

        await assert.rejects(
            () => startServer(config, silentLogger),
            /already been called|shutdownServer/i
        );
    });

    test('can restart after shutdownServer() resets state', async () => {
        const port = await getFreePort();
        const config = minimalConfig({ listen: { http: port, https: null } });

        await startServer(config, silentLogger);
        await shutdownServer();

        await assert.doesNotReject(() => startServer(config, silentLogger));
    });
});

