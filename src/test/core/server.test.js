// Unit-level: shutdownServer
// ---------------------------------------------------------------------------

describe('shutdownServer', () => {
    test('no-ops safely when nothing was started', async () => {
        await assert.doesNotReject(() => shutdownServer());
    });

    test('closes http server so further connections are refused', async () => {
        const port = await getFreePort();
        const config = minimalConfig({ listen: { http: port, https: null } });

        await startServer(config, silentLogger);
        await shutdownServer();

        // request to 127.0.0.1, not 'localhost' — avoids dual-stack happy-eyeballs
        // AggregateError on platforms (macOS) that try ::1 and 127.0.0.1 both.
        await assert.rejects(
            () => new Promise((resolve, reject) => {
                const req = http.request({ host: '127.0.0.1', port, timeout: 500 }, resolve);
                req.on('error', reject);
                req.end();
            }),
            (err) => {
                if (err.code === 'ECONNREFUSED') return true;
                if (err.name === 'AggregateError') {
                    return err.errors?.some((e) => e.code === 'ECONNREFUSED');
                }
                return false;
            }
        );
    });
});

// ---------------------------------------------------------------------------
// Integration: real request through the full pipeline
// (rateLimit -> routeMatch -> auth -> backendPhase -> forwardToBackend)
// ---------------------------------------------------------------------------

describe('integration: full request lifecycle', () => {
    let backend;
    let backendPort;

    before(async () => {
        backend = http.createServer((req, res) => {
            res.writeHead(200, { 'content-type': 'application/json' });
            res.end(JSON.stringify({ ok: true, path: req.url }));
        });
        backendPort = await getFreePort();
        await new Promise((resolve) => backend.listen(backendPort, resolve));
    });

    after(async () => {
        await new Promise((resolve) => backend.close(resolve));
    });

    test('proxies an HTTP request end-to-end through startServer()', async () => {
        const gatewayPort = await getFreePort();
        const config = minimalConfig({
            listen: { http: gatewayPort, https: null },
            backends: { web: [{ url: `http://127.0.0.1:${backendPort}`, weight: 1 }] },
            routes: [{ path: '/', backend: 'web' }]
        });

        await startServer(config, silentLogger);

        const res = await get(gatewayPort, '/anything');

        assert.equal(res.status, 200);
        const parsed = JSON.parse(res.body);
        assert.equal(parsed.ok, true);
    });

    test('returns 404 for unmatched route', async () => {
        const gatewayPort = await getFreePort();
        const config = minimalConfig({
            listen: { http: gatewayPort, https: null },
            backends: { web: [{ url: `http://127.0.0.1:${backendPort}`, weight: 1 }] },
            routes: [{ path: '/only-this', backend: 'web' }]
        });

        await startServer(config, silentLogger);

        const res = await get(gatewayPort, '/nope');

        assert.equal(res.status, 404);
    });

    test('returns 401 when route requires auth and no key given', async () => {
        const gatewayPort = await getFreePort();
        const config = minimalConfig({
            listen: { http: gatewayPort, https: null },
            backends: { web: [{ url: `http://127.0.0.1:${backendPort}`, weight: 1 }] },
            routes: [{ path: '/', backend: 'web', auth: true }],
            auth: { headerName: 'X-API-Key', keys: ['secret-123'], requiredByDefault: false }
        });

        await startServer(config, silentLogger);

        const res = await get(gatewayPort, '/protected');

        assert.equal(res.status, 401);
    });

    test('returns 502 when route points at a pool with no backends', async () => {
        const gatewayPort = await getFreePort();
        const config = minimalConfig({
            listen: { http: gatewayPort, https: null },
            backends: { web: [] },
            routes: [{ path: '/', backend: 'web' }]
        });

        await startServer(config, silentLogger);

        const res = await get(gatewayPort, '/anything');

        assert.equal(res.status, 502);
    });

    test('returns 429 once rate limit is exhausted', async () => {
        const gatewayPort = await getFreePort();
        const config = minimalConfig({
            listen: { http: gatewayPort, https: null },
            backends: { web: [{ url: `http://127.0.0.1:${backendPort}`, weight: 1 }] },
            routes: [{ path: '/', backend: 'web' }],
            ratelimit: { windowMs: 60_000, maxRequests: 2, burst: 0 }
        });

        await startServer(config, silentLogger);

        const results = [];
        for (let i = 0; i < 4; i++) {
            results.push((await get(gatewayPort, '/x')).status);
        }

        assert.ok(results.includes(429), `expected a 429 among ${results}`);
    });

    test('gateway responds correctly across N sequential requests (keepAlive sanity)', async () => {
        const gatewayPort = await getFreePort();
        const config = minimalConfig({
            listen: { http: gatewayPort, https: null },
            backends: { web: [{ url: `http://127.0.0.1:${backendPort}`, weight: 1 }] },
            routes: [{ path: '/', backend: 'web' }]
        });

        await startServer(config, silentLogger);

        for (let i = 0; i < 5; i++) {
            const res = await get(gatewayPort, `/req-${i}`);
            assert.equal(res.status, 200);
        }
    });

    test('shutdownServer() completes well within the shutdown timeout when idle', async () => {
        const gatewayPort = await getFreePort();
        const config = minimalConfig({
            listen: { http: gatewayPort, https: null },
            backends: { web: [{ url: `http://127.0.0.1:${backendPort}`, weight: 1 }] },
            routes: [{ path: '/', backend: 'web' }]
        });

        await startServer(config, silentLogger, { shutdownTimeoutMs: 2000 });

        const start = Date.now();
        await shutdownServer();
        const elapsed = Date.now() - start;

        assert.ok(elapsed < 2000, `shutdown took ${elapsed}ms, expected fast graceful close`);
    });
});