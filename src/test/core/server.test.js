function getFreePort() {
    return new Promise((resolve, reject) => {
        const srv = net.createServer();
        srv.listen(0, () => {
            const { port } = srv.address();
            srv.close(() => resolve(port));
        });
        srv.on('error', reject);
    });
}

const silentLogger = { info: () => { }, warn: () => { }, error: () => { } };

// Real config shape, per nexus.config.json:
//   backends is an OBJECT keyed by pool name -> array of {url, weight}
//   routes is an array of {path, backend: <pool name>}
function minimalConfig(overrides = {}) {
    return {
        listen: { http: null, https: null },
        logging: { level: 'silent' },
        backends: {},
        routes: [],
        healthcheck: { path: '/health', intervalMs: 60_000, unhealthyThreshold: 3, healthyThreshold: 2 },
        ratelimit: { windowMs: 60_000, maxRequests: 1000, burst: 0 },
        auth: { headerName: 'X-API-Key', keys: [], requiredByDefault: false },
        wal: { enabled: false },
        dashboard: { enabled: false },
        tls: { certPath: null, keyPath: null, sni: false },
        ...overrides
    };
}

function get(port, urlPath = '/') {
    return new Promise((resolve, reject) => {
        http.get({ host: '127.0.0.1', port, path: urlPath, timeout: 2000 }, (res) => {
            let data = '';
            res.on('data', (c) => (data += c));
            res.on('end', () => resolve({ status: res.statusCode, headers: res.headers, body: data }));
        }).on('error', reject);
    });
}

afterEach(async () => {
    await shutdownServer();
});

